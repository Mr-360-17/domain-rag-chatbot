"""Domain-Specific RAG Chatbot for PDF Question Answering - Streamlit interface.

Run:  streamlit run app.py
"""
from pathlib import Path

import streamlit as st

from document_loader import MAX_FILE_SIZE_MB, MAX_FILES, DocumentError, load_documents
from rag_pipeline import TOP_K, RAGPipeline, get_model_name, get_provider
from vector_store import MODEL_NAME, VectorStore, get_model

ROOT = Path(__file__).parent
SAMPLE_DIR = ROOT / "documents"
SAVED_INDEX = ROOT / "vector_store" / "saved_index"
EXAMPLES = [
    "How many earned leave days do employees get per year?",
    "How is monthly attendance calculated?",
    "What is the daily allowance for travel to a metro city?",
    "How quickly must a lost laptop be reported?",
]

st.set_page_config(page_title="Policy Document Chatbot", page_icon="📚", layout="wide")


@st.cache_resource(show_spinner="Loading the embedding model...")
def load_embedding_model():
    return get_model()


@st.cache_resource(show_spinner="Loading the sample document index...")
def load_sample_store() -> VectorStore:
    if VectorStore.exists(SAVED_INDEX):
        return VectorStore.load(SAVED_INDEX)
    files = [(p.name, p.read_bytes()) for p in sorted(SAMPLE_DIR.glob("*.pdf"))]
    store = VectorStore.build(load_documents(files)[0])
    store.save(SAVED_INDEX)
    return store


def set_store(store: VectorStore, label: str) -> None:
    st.session_state.store = store
    st.session_state.store_label = label
    st.session_state.messages = []


def render_sources(sources: list[dict]) -> None:
    if not sources:
        return
    pages = ", ".join(dict.fromkeys(f"{s['source']} p.{s['page']}" for s in sources))
    with st.expander(f"Sources: {pages}"):
        for s in sources:
            st.markdown(f"**{s['source']}**, page {s['page']} · similarity {s['score']:.2f}")
            st.caption(s["text"][:450] + ("..." if len(s["text"]) > 450 else ""))


load_embedding_model()
st.session_state.setdefault("messages", [])
st.session_state.setdefault("store", None)
st.session_state.setdefault("store_label", "")

# ---------- Sidebar: documents ----------
with st.sidebar:
    st.header("📄 Documents")
    uploads = st.file_uploader(
        f"Upload PDFs (up to {MAX_FILES} files, {MAX_FILE_SIZE_MB} MB each)",
        type=["pdf"], accept_multiple_files=True,
    )
    if uploads:
        st.caption("Selected: " + ", ".join(f.name for f in uploads))
    if st.button("Process Documents", type="primary", disabled=not uploads, width="stretch"):
        try:
            with st.spinner("Extracting text, chunking and creating embeddings..."):
                chunks, warnings = load_documents([(f.name, f.getvalue()) for f in uploads])
                store = VectorStore.build(chunks)
            set_store(store, f"{len(uploads)} uploaded file(s)")
            for w in warnings:
                st.warning(w)
            st.success(f"Indexed {len(chunks)} chunks from {len(store.sources)} document(s).")
        except DocumentError as err:
            st.error(str(err))

    if st.button("Use sample HR policy documents", width="stretch"):
        set_store(load_sample_store(), "sample HR policy documents")

    if st.session_state.store is not None:
        store = st.session_state.store
        st.markdown(f"**Active:** {st.session_state.store_label}")
        for name in store.sources:
            st.markdown(f"- {name}")
        st.caption(f"{len(store.chunks)} chunks in the FAISS index")
        if st.button("Clear documents", width="stretch"):
            st.session_state.store = None
            st.session_state.messages = []
            st.rerun()

    st.divider()
    st.subheader("Settings")
    provider = get_provider()
    llm = f"{provider.title()} `{get_model_name()}`" if provider else "not configured"
    st.caption(f"Embeddings: `{MODEL_NAME.split('/')[-1]}`  \nVector store: FAISS (cosine)  \n"
               f"LLM: {llm}  \nTop-k chunks: {TOP_K}")
    if not provider:
        st.warning("No GEMINI_API_KEY or GROQ_API_KEY found. The app will show the matching passages only.")
    st.divider()
    st.caption("Uploaded files are processed in memory and are not saved. "
               "Do not upload confidential documents without permission.")

# ---------- Main: chat ----------
st.title("📚 Domain-Specific RAG Chatbot")
st.write("Ask questions about your PDFs. Answers come only from the documents, with the source "
         "file and page number.")
st.info("Answers are generated by AI and may contain mistakes. Verify important or high-stakes "
        "information in the original document.", icon="⚠️")

if st.session_state.store is None:
    st.markdown("**To start:** upload PDFs and click **Process Documents** in the sidebar, or click "
                "**Use sample HR policy documents** to try four policy documents of a fictional company.")
    st.stop()

top_left, top_right = st.columns([5, 1])
with top_right:
    if st.button("Clear Chat", width="stretch"):
        st.session_state.messages = []
        st.rerun()

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])
        if message["role"] == "assistant":
            render_sources(message.get("sources", []))
            if message.get("seconds"):
                st.caption(f"Answered in {message['seconds']:.1f} s")

question = st.chat_input("Ask a question about the documents") or st.session_state.pop("pending", None)
if not st.session_state.messages and not question:
    st.caption("Try one of these:")
    cols = st.columns(2)
    for i, example in enumerate(EXAMPLES):
        if cols[i % 2].button(example, key=f"ex{i}", width="stretch"):
            st.session_state.pending = example
            st.rerun()

if question:
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)
    with st.chat_message("assistant"):
        with st.spinner("Searching the documents..."):
            try:
                result = RAGPipeline(st.session_state.store).answer(question)
            except Exception as err:  # network or API errors from the LLM provider
                st.error(f"The language model request failed: {err}")
                st.stop()
        st.markdown(result.text)
        render_sources(result.sources)
        st.caption(f"Answered in {result.seconds:.1f} s")
    st.session_state.messages.append({
        "role": "assistant", "content": result.text,
        "sources": result.sources, "seconds": result.seconds,
    })
